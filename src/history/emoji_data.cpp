QString categoryName(EmojiCategory cat) {
    switch (cat) {
    case EmojiCategory::People:      return QCoreApplication::translate("EmojiData", "Smileys & People");
    case EmojiCategory::Nature:      return QCoreApplication::translate("EmojiData", "Animals & Nature");
    case EmojiCategory::FoodDrink:   return QCoreApplication::translate("EmojiData", "Food & Drink");
    case EmojiCategory::Activity:    return QCoreApplication::translate("EmojiData", "Activity");
    case EmojiCategory::TravelPlaces:return QCoreApplication::translate("EmojiData", "Travel & Places");
    case EmojiCategory::Objects:     return QCoreApplication::translate("EmojiData", "Objects");
    case EmojiCategory::Symbols:     return QCoreApplication::translate("EmojiData", "Symbols");
    case EmojiCategory::Flags:       return QCoreApplication::translate("EmojiData", "Flags");
    }
    return QString();
}

