const QVector<EmojiEntry> &categoryEntries(EmojiCategory cat) {
    switch (cat) {
    case EmojiCategory::People:      return peopleEntries();
    case EmojiCategory::Nature:      return natureEntries();
    case EmojiCategory::FoodDrink:   return foodEntries();
    case EmojiCategory::Activity:    return activityEntries();
    case EmojiCategory::TravelPlaces:return travelEntries();
    case EmojiCategory::Objects:     return objectsEntries();
    case EmojiCategory::Symbols:     return symbolsEntries();
    case EmojiCategory::Flags:       return flagsEntries();
    }
    static const QVector<EmojiEntry> empty;
    return empty;
}

const QVector<EmojiEntry> &allEmojiEntries() {
    static const QVector<EmojiEntry> all = [] {
        QVector<EmojiEntry> result;
        for (int i = 1; i <= kEmojiCategoryCount; ++i) {
            result.append(categoryEntries(static_cast<EmojiCategory>(i)));
        }
        return result;
    }();
    return all;
}

